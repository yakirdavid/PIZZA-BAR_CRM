export function clone(o) {
  return JSON.parse(JSON.stringify(o));
}

// משלים שדות חסרים בהגדרות שמורות (למשל אחרי עדכון גרסה)
export function withDefaults(saved) {
  const d = clone(DEFAULT_SETTINGS);
  if (!saved) return d;
  const out = { ...d, ...saved };
  for (const k of ['numbering', 'business', 'images', 'ageGroups', 'extension', 'deposit', 'cancellation', 'pasta', 'internal', 'menu', 'quoteDefaults', 'whatsapp', 'notify', 'expenses']) {
    out[k] = { ...d[k], ...(saved[k] || {}) };
  }
  if ((saved.schema || 1) < 2) {
    // גרסה 2: סוגי אירוע חדשים ומספר פיצות גמיש
    const missing = ['מסיבת רווקות', 'מסיבת רווקים'].filter((t) => !out.eventTypes.includes(t));
    out.eventTypes = [...missing, ...out.eventTypes];
    const pizzaVar = (t) => String(t).replace(/\b6 סוגי פיצות/g, '{מספר_פיצות} סוגי פיצות');
    out.menuNote = pizzaVar(out.menuNote);
    out.terms = out.terms.map(pizzaVar);
    out.schema = 2;
  }
  if (out.schema < 3) {
    // גרסה 3: מספר מנות ראשונות לבחירה לכל מסלול
    out.packages = out.packages.map((p) => ({ ...p, starterCount: p.starterCount ?? (p.id === 'full' ? 4 : 0) }));
    out.schema = 3;
  }
  if (out.schema < 4) {
    // גרסה 4: מנות קבועות / מוסתרות / עם הערה בתפריט (לטופס בחירת המנות ולהזמנה)
    const norm = (n) => String(n || '').replace(/[׳'’`]/g, "'").trim();
    const mark = (list, name, extra) =>
      (list || []).map((x) => (norm(x.name) === norm(name) && !('fixed' in x || 'hidden' in x || 'note' in x) ? { ...x, ...extra } : x));
    out.menu = {
      ...out.menu,
      starters: mark(out.menu.starters, 'פוקאצ׳ה', { fixed: true }),
      desserts: mark(
        mark(mark(out.menu.desserts, 'קלצונה נוטלה', { fixed: true }), 'פיצה שחיתות', { hidden: true }),
        'מלבי',
        { note: 'בתוספת 10 ₪ לאדם' }
      ),
    };
    out.schema = 4;
  }
  return out;
}
